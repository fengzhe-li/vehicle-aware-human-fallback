"""Genuine AutoVLA Inference Module (Phase B).

Loads the pretrained `AutoVLA` (`Zewei-Zhou/AutoVLA` -> `AutoVLA_PDMS_89.ckpt`,
built on `Qwen/Qwen2.5-VL-3B-Instruct` with 2,048 physical `<action_k>` tokens),
preprocesses real 12-image multi-view driving history (`CAM_F0`, `CAM_L0`, `CAM_R0`
over 4 frames at 2 Hz) and ego kinematics (`v`, `a`, driving command), runs
real neural network forward generation (`do_sample=False`), and decodes the
predicted `<action_k>` tokens into physical ego-frame coordinates `(t_s, x_m, y_m, heading_rad)`.

IMPORTANT:
- AutoVLA does NOT predict a human takeover request (`predicts_human_takeover_request = False`).
- No mock or fabricated trajectories are generated by this module.
"""

