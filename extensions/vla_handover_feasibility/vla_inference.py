# Exact prompt templates from ucla-mobility/AutoVLA (autovla/configs/mix_sft.yaml & grpo_cot.yaml)
AUTOVLA_FAST_PROMPT_TEMPLATE = (
    "Suppose you are driving, and I'm providing you with the image captured by the car's "
    "<FRONT VIEW>, <FRONT LEFT VIEW>, <FRONT RIGHT VIEW>, theego velocity is {ego_v:.2f} m/s, "
    "the ego acceleration is {ego_a:.2f} m/s^2, and the driving command is {driving_cmd}. "
    "Generate the planned trajectory for the next 5 seconds."
)

AUTOVLA_COT_PROMPT_TEMPLATE = (
    "Suppose you are driving, and I'm providing you with the image captured by the car's "
    "<FRONT VIEW>, <FRONT LEFT VIEW>, <FRONT RIGHT VIEW>, theego velocity is {ego_v:.2f} m/s, "
    "the ego acceleration is {ego_a:.2f} m/s^2, and the driving command is {driving_cmd}. "
    "Please reason step by step before generating the planned trajectory for the next 5 seconds."
)

AUTOVLA_PIXELS_PER_IMAGE = 128 * 28 * 28  # 100,352 pixels matching grpo_cot.yaml


def get_runtime_environment_metadata(device: str) -> dict[str, Any]:
    """Record software versions, hardware device, peak RSS, and swap metadata for reproducibility."""
    import resource
    import subprocess

    hw_model = platform.machine()
    swap_used_mb: float | None = None
    if platform.system() == "Darwin":
        try:
            brand = subprocess.check_output(
                ["sysctl", "-n", "machdep.cpu.brand_string"], text=True, timeout=2
            ).strip()
            if brand:
                hw_model = f"{brand} ({platform.machine()})"
        except Exception:
            pass
        try:
            swap_out = subprocess.check_output(
                ["sysctl", "-n", "vm.swapusage"], text=True, timeout=2
            ).strip()
            m_swap = re.search(r"used\s*=\s*([0-9.]+)M", swap_out)
            if m_swap:
                swap_used_mb = round(float(m_swap.group(1)), 2)
        except Exception:
            pass

    ru_maxrss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    peak_rss_mb = round(ru_maxrss / (1024.0 * 1024.0), 2) if platform.system() == "Darwin" else round(ru_maxrss / 1024.0, 2)

    return {
        "python_version": platform.python_version(),
        "platform": platform.platform(),
        "hardware": hw_model,
        "device": str(device),
        "torch_version": torch.__version__,
        "transformers_version": transformers.__version__,
        "mps_available": bool(torch.backends.mps.is_available()),
        "cuda_available": bool(torch.cuda.is_available()),
        "peak_rss_mb": peak_rss_mb,
        "swap_used_mb": swap_used_mb,
    }


def build_autovla_user_message(
    front_images: list[str | Path],
    front_left_images: list[str | Path],
    front_right_images: list[str | Path],
    ego_speed_mps: float,
    ego_accel_mps2: float,
    driving_command: str,
    use_cot: bool = False,
    pixels_per_image: int = AUTOVLA_PIXELS_PER_IMAGE,
) -> tuple[list[dict[str, Any]], str]:
    """Construct the exact multimodal message list expected by AutoVLA (`process_input`)."""
    template = AUTOVLA_COT_PROMPT_TEMPLATE if use_cot else AUTOVLA_FAST_PROMPT_TEMPLATE
    prompt_str = template.format(
        ego_v=float(ego_speed_mps),
        ego_a=float(ego_accel_mps2),
        driving_cmd=str(driving_command).lower(),
    )

    view_map = {
        "<FRONT VIEW>": front_images,
        "<FRONT LEFT VIEW>": front_left_images,
        "<FRONT RIGHT VIEW>": front_right_images,
    }
    pattern = "|".join(map(re.escape, view_map.keys()))
    parts = re.split(f"({pattern})", prompt_str)

    content: list[dict[str, Any]] = []
    for part in parts:
        if part in view_map:
            for img_path in view_map[part]:
                content.append(
                    {
                        "type": "image",
                        "image": str(Path(img_path).resolve()),
                        "min_pixels": pixels_per_image,
                        "max_pixels": pixels_per_image,
                    }
                )
        elif part.strip():
            content.append({"type": "text", "text": part.strip()})

    messages = [{"role": "user", "content": content}]
    return messages, prompt_str


def parse_cot_and_actions(
    raw_text: str,
    generated_token_ids: list[int],
    action_tokenizer: AutoVLAActionTokenizer,
) -> tuple[str | None, list[int], list[int], bool, str]:
    """Extract optional CoT reasoning text, action token IDs, and codebook indices from AutoVLA output."""
    action_ids_from_tokens = [
        int(tid)
        for tid in generated_token_ids
        if action_tokenizer.base_vocab_offset <= int(tid) < action_tokenizer.base_vocab_offset + action_tokenizer.n_bins
    ]
    codebook_from_tokens = action_tokenizer.extract_codebook_indices_from_token_ids(generated_token_ids)
    codebook_from_text = action_tokenizer.extract_codebook_indices_from_text(raw_text)

    codebook_indices = codebook_from_tokens if len(codebook_from_tokens) >= len(codebook_from_text) else codebook_from_text
    if not action_ids_from_tokens and codebook_indices:
        action_ids_from_tokens = [action_tokenizer.base_vocab_offset + idx for idx in codebook_indices]

    # Extract reasoning text before `<action_` tags
    first_action_pos = raw_text.find("<action_")
    cot_text: str | None = None
    if first_action_pos > 0:
        prefix_txt = raw_text[:first_action_pos].strip()
        if prefix_txt:
            cot_text = prefix_txt

    notes: list[str] = []
    if len(codebook_indices) == DEFAULT_HORIZON_STEPS:
        valid = True
        notes.append(f"Decoded {len(codebook_indices)} action tokens over {DEFAULT_HORIZON_STEPS * DEFAULT_DT_S:.1f}s horizon.")
    elif len(codebook_indices) > DEFAULT_HORIZON_STEPS:
        valid = True
        notes.append(
            f"Generated {len(codebook_indices)} action tokens; truncated to first {DEFAULT_HORIZON_STEPS} steps (5.0s horizon)."
        )
        codebook_indices = codebook_indices[:DEFAULT_HORIZON_STEPS]
        action_ids_from_tokens = action_ids_from_tokens[:DEFAULT_HORIZON_STEPS]
    else:
        valid = False
        notes.append(
            f"Incomplete action token sequence: expected {DEFAULT_HORIZON_STEPS} tokens, got {len(codebook_indices)}."
        )

    return cot_text, action_ids_from_tokens, codebook_indices, valid, " ".join(notes)


class AutoVLAInferenceEngine:
    """Genuine AutoVLA inference runner using `Qwen2_5_VLForConditionalGeneration`."""

    def __init__(
        self,
        model_dir: str | Path = DEFAULT_AUTOVLA_MODEL_DIR,
        codebook_path: str | Path = DEFAULT_CODEBOOK_PATH,
        device: str | None = None,
    ) -> None:
        self.model_dir = Path(model_dir)
        if not self.model_dir.exists():
            raise FileNotFoundError(
                f"AutoVLA converted checkpoint directory not found at {self.model_dir}. "
                "Run `download_convert_autovla.py` first."
            )
        self.action_tokenizer = AutoVLAActionTokenizer(codebook_path=codebook_path)

        if device is None:
            if torch.backends.mps.is_available():
                self.device = "mps"
            elif torch.cuda.is_available():
                self.device = "cuda"
            else:
                self.device = "cpu"
        else:
            self.device = device

        self.dtype = torch.bfloat16

        index_file = self.model_dir / "model.safetensors.index.json"
        self.index_metadata: dict[str, Any] = {}
        if index_file.exists():
            with open(index_file, "r", encoding="utf-8") as f:
                self.index_metadata = json.load(f).get("metadata", {})

        self.processor = AutoProcessor.from_pretrained(str(self.model_dir))
        if len(self.processor.tokenizer) != BASE_QWEN_VOCAB_SIZE + ACTION_VOCAB_SIZE:
            raise ValueError(
                f"Unexpected tokenizer length {len(self.processor.tokenizer)}; "
                f"expected {BASE_QWEN_VOCAB_SIZE + ACTION_VOCAB_SIZE}"
            )

        self.model = Qwen2_5_VLForConditionalGeneration.from_pretrained(
            str(self.model_dir),
            dtype=self.dtype,
            device_map=self.device,
            low_cpu_mem_usage=True,
        )
        self.model.eval()
        if self.device == "mps" and hasattr(self.model, "model") and hasattr(self.model.model, "visual"):
            self.model.model.visual.register_forward_hook(
                lambda _mod, _inp, _out: torch.mps.empty_cache()
            )

    def predict_scene(
        self,
        scene_meta: dict[str, Any],
        data_root: str | Path = DEFAULT_DATA_DIR,
        use_cot: bool = False,
        max_new_tokens: int | None = None,
    ) -> VLAPredictionArtifact:
        """Run a genuine single-scene (batch_size=1) AutoVLA forward pass on a real driving scene."""
        import gc

        root = Path(data_root)
        cams = scene_meta["camera_images"]
        front_imgs = [root / p for p in cams["front_camera"]]
        left_imgs = [root / p for p in cams["front_left_camera"]]
        right_imgs = [root / p for p in cams["front_right_camera"]]

        ego = scene_meta["ego_state"]
        v0 = float(ego["speed_mps"])
        a0 = float(ego["accel_norm_mps2"])
        cmd = str(ego["effective_driving_command"])
        raw_cmd = str(ego["raw_driving_command"])

        messages, prompt_text = build_autovla_user_message(
            front_images=front_imgs,
            front_left_images=left_imgs,
            front_right_images=right_imgs,
            ego_speed_mps=v0,
            ego_accel_mps2=a0,
            driving_command=cmd,
            use_cot=use_cot,
        )

        chat_text = self.processor.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True
        )
        image_inputs, video_inputs = process_vision_info([messages])
        inputs = self.processor(
            text=[chat_text],
            images=image_inputs,
            videos=video_inputs,
            padding=True,
            return_tensors="pt",
        ).to(self.device)
        del messages, image_inputs, video_inputs

        if max_new_tokens is None:
            max_new_tokens = 256 if use_cot else 52

        if self.device == "mps":
            torch.mps.synchronize()
        t_start = time.perf_counter()

        with torch.inference_mode():
            generated_ids = self.model.generate(
                **inputs,
                max_new_tokens=max_new_tokens,
                do_sample=False,
                use_cache=True,
            )

        if self.device == "mps":
            torch.mps.synchronize()
        latency_ms = (time.perf_counter() - t_start) * 1000.0

        prompt_len = inputs.input_ids.shape[1]
        trimmed_ids = generated_ids[0, prompt_len:].detach().cpu().tolist()
        del inputs, generated_ids
        gc.collect()
        if self.device == "mps":
            torch.mps.empty_cache()
        raw_output_text = self.processor.decode(
            trimmed_ids, skip_special_tokens=True, clean_up_tokenization_spaces=False
        )

        cot_text, action_token_ids, codebook_indices, is_valid, validity_notes = parse_cot_and_actions(
            raw_text=raw_output_text,
            generated_token_ids=trimmed_ids,
            action_tokenizer=self.action_tokenizer,
        )

        predicted_waypoints = self.action_tokenizer.decode_indices_to_waypoints(codebook_indices)
        gt_waypoints = [
            TrajectoryWaypoint(
                step=int(g["step"]),
                t_s=float(g["t_s"]),
                x_m=float(g["x_m"]),
                y_m=float(g["y_m"]),
                heading_rad=float(g["heading_rad"]),
            )
            for g in scene_meta.get("ground_truth_future_trajectory", [])
        ]

        mode_str = "cot" if use_cot else "fast"
        return VLAPredictionArtifact(
            scene_id=str(scene_meta["scene_id"]),
            inference_mode=mode_str,
            model_name="AutoVLA (Qwen2.5-VL-3B-Instruct + 2048 Physical Action Tokens)",
            checkpoint_repo=str(self.index_metadata.get("source_repo", "Zewei-Zhou/AutoVLA")),
            checkpoint_file=str(self.index_metadata.get("source_checkpoint", "AutoVLA_PDMS_89.ckpt")),
            checkpoint_etag=str(self.index_metadata.get("source_etag", "")),
            base_vlm_architecture=str(self.index_metadata.get("base_architecture", "Qwen/Qwen2.5-VL-3B-Instruct")),
            dataset_source=str(scene_meta["dataset_source"]),
            log_file=str(scene_meta["log_file"]),
            frame_token=str(scene_meta["frame_token"]),
            scene_name=str(scene_meta["scene_name"]),
            map_location=str(scene_meta["map_location"]),
            timestamp_us=int(scene_meta["timestamp_us"]),
            ego_initial_speed_mps=round(v0, 4),
            ego_initial_accel_mps2=round(float(ego["ax_mps2"]), 4),
            ego_vx_mps=round(float(ego["vx_mps"]), 4),
            ego_vy_mps=round(float(ego["vy_mps"]), 4),
            ego_ax_mps2=round(float(ego["ax_mps2"]), 4),
            ego_ay_mps2=round(float(ego["ay_mps2"]), 4),
            driving_command=cmd,
            raw_driving_command=raw_cmd,
            prompt_text=prompt_text,
            raw_generated_text=raw_output_text,
            cot_reasoning_text=cot_text,
            action_token_ids=action_token_ids,
            action_codebook_indices=codebook_indices,
            prediction_valid=is_valid,
            validity_notes=validity_notes,
            coordinate_frame="ego_vehicle_local_at_t0 (+x forward m, +y left m, heading rad CCW)",
            units={"t_s": "s", "x_m": "m", "y_m": "m", "heading_rad": "rad", "speed": "m/s", "accel": "m/s^2"},
            horizon_s=round(len(predicted_waypoints) * self.action_tokenizer.dt_s, 3),
            dt_s=self.action_tokenizer.dt_s,
            predicted_waypoints=predicted_waypoints,
            ground_truth_waypoints=gt_waypoints,
            inference_latency_ms=round(latency_ms, 2),
            environment_metadata=get_runtime_environment_metadata(self.device),
            predicts_human_takeover_request=False,
        )


def save_prediction_artifact(
    artifact: VLAPredictionArtifact,
    out_dir: str | Path = DEFAULT_PREDICTIONS_DIR,
) -> Path:
    """Save a `VLAPredictionArtifact` as a reproducible JSON file."""
    target_dir = Path(out_dir)
    target_dir.mkdir(parents=True, exist_ok=True)
    out_path = target_dir / f"{artifact.scene_id}_{artifact.inference_mode}.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(artifact.to_dict(), f, indent=2)
    return out_path


def load_prediction_artifact(path: str | Path) -> VLAPredictionArtifact:
    """Load a saved `VLAPredictionArtifact` from JSON."""
    with open(Path(path), "r", encoding="utf-8") as f:
        d = json.load(f)
    pred_wps = [TrajectoryWaypoint(**w) for w in d["predicted_waypoints"]]
    gt_wps = [TrajectoryWaypoint(**w) for w in d.get("ground_truth_waypoints", [])]
    d["predicted_waypoints"] = pred_wps
    d["ground_truth_waypoints"] = gt_wps
    return VLAPredictionArtifact(**d)
